"""Fill ЕМКО data gaps from the OCR'd tables, and write clean data files.

For each Table x.2 garment: start from the pilot's validated draft rows, then
add what the OCR pipeline reads AND verifies itself:
  - row 9 (31–37), accepted only with status ok/repaired/aligned (row identities);
  - к81, from row 81's note, or 0 when the table has no row 81 and row 82
    starts at 131 (emko_ocr.k81).
A value the OCR verifies that disagrees with the pilot's is a conflict: it is
reported and the file is not written. For the graded jacket (Table 1.4), row 91
and к81 come from Table 1.2's own formula/note for the same garment, parsed
from its OCR text.

usage: python scripts/emko_fill_gaps.py   (writes data/emko/*_176-100-88.yaml, jacket_graded.yaml)
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'scripts'))
from ccat.sources import emko, emko_ocr     # noqa: E402
from emko_ocr_bench import TABLES, lines    # noqa: E402

OUT = ROOT / 'data' / 'emko'
GARMENTS = {'2.2': 'coat_demi', '3.2': 'coat_winter', '4.2': 'summer_jacket', '5.2': 'jacket_insulated',
            '6.2': 'waistcoat'}
VERIFIED = ('ok', 'repaired', 'aligned')
# Hand-transcribed model-construction rows (Table x.3) follow this line in a data file;
# a rewrite keeps everything from it on.
IMK_MARK = '# ---- ИМК'


def table_rows(table):
    from emko_ocr_bench import read_all
    rows, _ = read_all()[table]
    by_n = {}
    for r in rows:
        by_n.setdefault(r['n'], r)
    return rows, by_n


def scale_formula(by_n, n):
    """Row n printed as 'c·|A–B|' (e.g. row 91: 0,5/95—931/) -> (c, row whose segment is A–B)."""
    r = by_n.get(n)
    m = r and re.search(r'(\d+[,.]\d+)\s*/\s*(\d+)\s*[—–-]+\s*(\d+)\s*/', r['raw'])
    if not m:
        return None
    c, a, b = float(m.group(1).replace(',', '.')), m.group(2), m.group(3)
    for k, rr in by_n.items():
        seg = rr['seg'] or ''
        if re.fullmatch(rf'{a}\s*[—–-]+\s*{b}', seg):
            return c, k
    return None


def garment_file(table, name):
    doc = emko.load(ROOT / 'pilot' / 'emko' / f'{name}_176-100-88.yaml')
    rows, by_n = table_rows(table)
    draft = {float(k) if '.' in str(k) else int(k): float(v) for k, v in doc['draft'].items()}
    prov, conflicts = {}, []
    r9 = by_n.get(9)
    if r9 and r9['status'] in VERIFIED:
        v = r9['cells']['draft']
        if 9 in draft and abs(draft[9] - v) > 1e-9:
            conflicts.append(f'row 9: pilot {draft[9]} vs OCR {v}')
        draft[9] = v
        prov[9] = f'OCR, row identities ({r9["status"]})'
    for k, row in emko.PILOT_NAMES.items():                 # sleeve and check rows the pilot kept by name
        v = (doc.get('sleeve_rows') or {}).get(k, doc.get(k) if k == 'dp' else None)
        if isinstance(v, (int, float)) and v == v:
            draft[float(row) if '.' in row else int(row)] = float(v)
    coeff = {}
    if doc.get('sleeve'):
        k, how = emko_ocr.k81(rows)
        old = (doc.get('sleeve_rows') or {}).get('k81')
        if k is None:
            conflicts.append(f'к81 unresolved: {how}')
        else:
            coeff['k81'] = k
            prov['k81'] = how + (f' (pilot had assumed {old})' if old is not None and old != k else '')
            if old is None:
                prov['k81'] += ' (pilot had defaulted to 0.4)' if k != 0.4 else ''
    return doc, draft, coeff, prov, conflicts


def write_garment(table, name):
    doc, draft, coeff, prov, conflicts = garment_file(table, name)
    if conflicts:
        return f'{name}: NOT WRITTEN, ' + '; '.join(conflicts)
    lines_ = [f'# {doc["name"]}: ЕМКО СЭВ т.3 Table {table}. Generated by scripts/emko_fill_gaps.py.',
              '# Draft rows: pilot transcription (OCR + arithmetic + vision, pilot/emko/'
              f'{name}_176-100-88.yaml) unless marked.',
              f'name: {doc["name"]}', f'source: {{book: "ЕМКО СЭВ т.3", table: "{table}", size: "176-100-88"}}',
              f'sleeve: {str(bool(doc.get("sleeve"))).lower()}', 'draft:']
    for k in sorted(draft):
        note = f'   # {prov[k]}' if k in prov else ''
        lines_.append(f'  {k}: {draft[k]:g}{note}')
    if coeff:
        lines_.append('coefficients:')
        for k, v in coeff.items():
            lines_.append(f'  {k}: {v:g}   # {prov[k]}')
    path = OUT / f'{name}_176-100-88.yaml'
    if path.exists():
        old = path.read_text(encoding='utf-8').splitlines()
        tail = [i for i, l in enumerate(old) if l.startswith(IMK_MARK)]
        lines_ += old[tail[0]:] if tail else []
    path.write_text('\n'.join(lines_) + '\n', encoding='utf-8')
    return f'{name}: written; ' + '; '.join(f'{k}: {v}' for k, v in prov.items())


def write_graded():
    _, by_n = table_rows('1.2')
    f91 = scale_formula(by_n, 91)
    k, how = emko_ocr.k81(table_rows('1.2')[0])
    if not f91 or k is None:
        return f'graded: NOT WRITTEN (row 91 formula {f91}, к81 {how})'
    c, ref = f91
    doc = {'table': 'pilot/emko/jacket_table14.yaml',
           'derived': {'r91': f'{c:g} * r{ref}'}, 'coefficients': {'k81': k}}
    text = ('# Graded men\'s jacket, Table 1.4. Rows the table does not print come from the same\n'
            '# garment\'s Table 1.2, read by scripts/emko_fill_gaps.py from its OCR text:\n'
            f'#   row 91 = {c:g}·|95–931| (Table 1.2 formula) -> r91 = {c:g} * r{ref}\n'
            f'#   к81 = {k:g} ({how}, Table 1.2)\n' + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False))
    (OUT / 'jacket_graded.yaml').write_text(text, encoding='utf-8')
    return f'graded: written (r91 = {c:g}·r{ref}, к81 = {k:g})'


if __name__ == '__main__':
    for t, name in GARMENTS.items():
        print(write_garment(t, name))
    print(write_graded())
