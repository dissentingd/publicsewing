// The garment family tree's coverage: reads garments/tree.yaml and garments/elements.yaml, works out
// which garment types are built, buildable from the library as it stands, partly buildable or
// blocked, and which missing elements block the most types. Writes garments/COVERAGE.md.
// Usage: node tools/garments.mjs [--check]     (run in designs/; --check fails if COVERAGE.md is stale)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const dir = new URL('../garments/', import.meta.url)
export const load = () => ({
  tree: parse(readFileSync(new URL('tree.yaml', dir), 'utf8')).nodes,
  freesewing: parse(readFileSync(new URL('tree.yaml', dir), 'utf8')).freesewingDesigns,
  elements: parse(readFileSync(new URL('elements.yaml', dir), 'utf8')),
})

const mark = { built: '●', listed: '◆', buildable: '◐', partial: '◔', gap: '○', group: '' }

/** A type's coverage: built, buildable (all traits covered), partial (none missing) or gap */
export function coverage(node, elements) {
  if (node.designs?.length || node.variants?.length) return 'built'
  if (node.freesewing?.length && !node.traits) return 'listed'
  if (!node.traits) return 'group'
  const st = node.traits.map((t) => elements[t]?.status)
  if (node.freesewing?.length) return 'listed'
  if (st.includes('gap') || node.knit) return 'gap'
  return st.includes('partial') ? 'partial' : 'buildable'
}

export function render({ tree, elements: E }) {
  const elements = E.elements
  const kids = {}
  for (const [id, n] of Object.entries(tree)) (kids[n.parent ?? ''] ??= []).push(id)
  const cov = Object.fromEntries(Object.entries(tree).map(([id, n]) => [id, coverage(n, elements)]))
  const leaves = Object.keys(tree).filter((id) => cov[id] !== 'group')
  const count = (s) => leaves.filter((id) => cov[id] === s).length

  const out = []
  out.push('# Garment coverage', '')
  out.push('Generated by `node tools/garments.mjs` from [tree.yaml](tree.yaml) and [elements.yaml](elements.yaml): edit those, not this. See [README.md](README.md).', '')
  out.push(`**${leaves.length} garment types:** ${count('built')} built by us ●, ${count('listed')} to list from FreeSewing ◆ (theirs, credited), ${count('buildable')} buildable now from our library ◐, ${count('partial')} partly buildable ◔ (an element is partial), ${count('gap')} blocked ○ (an element is missing, or it's knit).`, '')
  out.push('A FreeSewing design listed on our site adds a garment, not an element: our library can only build on a FreeSewing design we adopt as a block, as Brian is. The FreeSewing column says which design or block would supply each missing element.', '')

  // Missing elements, by how many unbuilt types each blocks
  out.push('## What to build next: missing elements', '')
  out.push('Each gap or partial element, with the unbuilt garment types that need it. A type is unblocked when all its elements are covered.', '')
  out.push('| Element | Status | Blocks | From FreeSewing | Types |', '|---|---|---|---|---|')
  const blocks = Object.entries(elements)
    .filter(([, e]) => e.status !== 'covered')
    .map(([k, e]) => [k, e, leaves.filter((id) => !['built', 'listed'].includes(cov[id]) && tree[id].traits?.includes(k))])
    .sort((a, b) => b[2].length - a[2].length || a[0].localeCompare(b[0]))
  for (const [k, e, ts] of blocks) out.push(`| ${e.name} (\`${k}\`) | ${e.status} | ${ts.length} | ${(e.freesewing ?? []).join(', ')} | ${ts.map((t) => tree[t].name).join(', ')} |`)
  out.push('')

  // The tree
  out.push('## The tree', '')
  out.push("● built by us · ◆ to list from FreeSewing · ◐ buildable now · ◔ partly buildable · ○ blocked. Our designs in brackets, FreeSewing's in braces; missing elements after the dash.", '')
  const walk = (id, depth) => {
    const n = tree[id]
    const c = cov[id]
    let line = `${'  '.repeat(depth)}- ${mark[c] ? mark[c] + ' ' : ''}${depth < 2 ? `**${n.name}**` : n.name}`
    if (n.designs?.length || n.variants?.length) line += ` [${[...(n.designs ?? []), ...(n.variants ?? [])].join(', ')}]`
    if (n.freesewing?.length) line += ` {FreeSewing: ${n.freesewing.join(', ')}}`
    if (c === 'gap' || c === 'partial') {
      const miss = (n.traits ?? []).filter((t) => elements[t]?.status !== 'covered')
      if (miss.length) line += ` — ${miss.join(', ')}`
      if (n.knit) line += ' — knit'
    }
    if (n.note) line += ` _(${n.note})_`
    out.push(line)
    for (const k of kids[id] ?? []) walk(k, depth + 1)
  }
  for (const root of kids[''] ?? []) walk(root, 0)
  out.push('')

  // Elements by group
  out.push('## Elements', '')
  for (const [g, gname] of Object.entries(E.groups)) {
    out.push(`### ${gname}`, '', '| Element | Status | Built by | Seen in | FreeSewing |', '|---|---|---|---|---|')
    for (const [k, e] of Object.entries(elements).filter(([, e]) => e.group === g)) {
      out.push(`| ${e.name} (\`${k}\`) | ${e.status}${e.note ? `: ${e.note}` : ''} | ${(e.lib ?? []).map((l) => `\`${l}\``).join(', ')} | ${(e.seen ?? []).join(', ')} | ${(e.freesewing ?? []).join(', ')} |`)
    }
    out.push('')
  }
  return out.join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const md = render(load())
  const file = new URL('COVERAGE.md', dir)
  if (process.argv.includes('--check')) {
    const old = readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
    if (old !== md) {
      console.error('garments/COVERAGE.md is stale: run node tools/garments.mjs')
      process.exit(1)
    }
  } else {
    writeFileSync(file, md)
    console.log(`wrote ${fileURLToPath(file)}`)
  }
}
